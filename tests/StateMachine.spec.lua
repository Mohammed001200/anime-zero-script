local StateMachine = require("../src/Core/StateMachine")
local Configuration = require("../src/Core/Configuration")
local Signal = require("../src/Utils/Signal")
local Cleanup = require("../src/Utils/Cleanup")
local Mock = require("./MockDungeon")
return function(t)
	t.it("integration cleanup failure does not prevent emergency stop or remaining disposal", function()
		local h = Mock.harness()
		h.controller:Start()
		h:advance(2)
		function h.mock:cancelCombat()
			error("Cleanup exception")
		end
		h.controller:Stop("Emergency stop")
		t.equal(h.controller.enabled, false)
		t.equal(h.mock.destination, nil)
		h.controller:Destroy()
		t.equal(h.mock.destroyCount, 1)
		t.equal(h.driver.destroyed, 1)
		h.config:Destroy()
		h.logger:Destroy()
	end)
	t.it("state machine rejects unknown states and deduplicates notifications", function()
		local machine, changes = StateMachine.new(), 0
		machine.Changed:Connect(function()
			changes += 1
		end)
		machine:Set("FIND_NPCS", "search")
		machine:Set("FIND_NPCS", "search")
		t.equal(changes, 1)
		t.equal(
			pcall(function()
				machine:Set("SPAWN_TELEPORT")
			end),
			false
		)
		machine:Destroy()
	end)
	t.it("configuration validates values and clamps follow distance", function()
		local config = Configuration.new()
		t.equal(config:Set("attackRange", 3), true)
		t.equal(config:Get().followDistance, 3)
		t.equal(config:Set("movementTimeout", 0 / 0), false)
		t.equal(config:Set("movementMode", "Teleport"), false)
		t.equal(config:Set("unknown", true), false)
		config:Set("movementSpeed", 1000)
		t.equal(config:Get().movementSpeed, 32)
		config:Destroy()
	end)
	t.it("preferences round trip deterministically and reset", function()
		local first = Configuration.new()
		first:Set("attackRange", 15)
		first:Set("followDistance", 12)
		first:Set("autoRetry", true)
		local second = Configuration.new(first:Export())
		t.equal(second:Get().followDistance, 12)
		t.equal(second:Get().autoRetry, true)
		second:Reset()
		t.equal(second:Get().autoRetry, false)
		t.equal(second:Load({ version = 99 }), false)
		first:Destroy()
		second:Destroy()
	end)
	t.it("signal disconnect and cleanup are idempotent", function()
		local signal, count, cleanup = Signal.new(), 0, Cleanup.new()
		cleanup:Add(signal:Connect(function()
			count += 1
		end))
		signal:Fire()
		cleanup:Destroy()
		cleanup:Destroy()
		signal:Fire()
		t.equal(count, 1)
		signal:Destroy()
	end)
	t.it("repeated start does not duplicate work", function()
		local h = Mock.harness()
		h.controller:Start()
		h.controller:Start()
		h:advance(1.5)
		assert(#h.mock.attacks <= 1)
		h:destroy()
	end)
	t.it("emergency stop immediately cancels movement and combat", function()
		local h = Mock.harness()
		h.controller:Start()
		h:advance(1.1)
		h.controller:Stop("Emergency stop")
		t.equal(h.mock.destination, nil)
		t.equal(h.controller.enabled, false)
		local attacks = #h.mock.attacks
		h:advance(3)
		t.equal(#h.mock.attacks, attacks)
		t.equal(h.controller.machine.state, "IDLE")
		h:destroy()
	end)
	t.it("controller destroy releases dependencies exactly once", function()
		local h = Mock.harness()
		h.controller:Start()
		h:advance(1.1)
		h.controller:Destroy()
		h.controller:Destroy()
		h:advance(2)
		t.equal(h.driver.destroyed, 1)
		t.equal(h.mock.destroyCount, 1)
		t.equal(h.mock.destination, nil)
		t.equal(h.controller:Start(), false)
		h.config:Destroy()
		h.logger:Destroy()
	end)
	t.it("adapter exceptions produce a visible error and cancel actions", function()
		local h = Mock.harness()
		h.mock.throwAttack = true
		h.controller:Start()
		h:advance(3)
		t.equal(h.controller.machine.state, "ERROR")
		t.equal(h.controller.enabled, false)
		assert(string.find(h.controller.status.lastError, "Mock combat exception"))
		h:destroy()
	end)
	t.it("unconfigured integration fails closed without movement", function()
		local Adapter = require("../src/Game/AnimeZeroAdapter")
		local adapter = Adapter.new()
		t.equal(adapter:snapshot().ready, false)
		t.equal(adapter.capabilities.attack, false)
		t.equal(adapter:attack("NPC", "anything", "run"), false)
		adapter:destroy()
	end)
end
